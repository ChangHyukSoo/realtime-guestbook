import { test, expect } from '@playwright/test';

test('그림 등록, 댓글, 저장 유지와 모바일 레이아웃', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByText('데모 모드')).toBeVisible();
  await expect(page.locator('.entry-card')).toHaveCount(6);
  await page.getByRole('button', { name: '나의 한 조각 남기기' }).click();
  await page.getByRole('button', { name: '마음 등록하기' }).click();
  await expect(page.getByRole('status')).toContainText('먼저 남겨');
  const box = await page.locator('canvas').boundingBox();
  if (!box) throw new Error('Canvas missing');
  await page.mouse.move(box.x + 50, box.y + 50);
  await page.mouse.down();
  await page.mouse.move(box.x + 160, box.y + 110, { steps: 10 });
  await page.mouse.up();
  await page.getByRole('button', { name: '마음 등록하기' }).click();
  await expect(page.locator('.entry-card')).toHaveCount(7);
  await page.locator('.entry-card').first().click();
  await page.getByRole('textbox', { name: '닉네임' }).fill('방문자');
  await page.getByRole('textbox', { name: '댓글', exact: true }).fill('다정한 하루 보내세요.');
  await page.getByRole('button', { name: '댓글 등록', exact: true }).click();
  await expect(page.locator('.comment')).toContainText('다정한 하루 보내세요.');
  await page.getByRole('button', { name: '목록으로 돌아가기' }).click();
  await page.reload();
  await expect(page.locator('.entry-card')).toHaveCount(7);
  await page.locator('.entry-card').first().click();
  await expect(page.locator('.comment')).toHaveCount(1);
  await page.getByRole('button', { name: '목록으로 돌아가기' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('h1')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'artifacts/mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.screenshot({ path: 'artifacts/desktop.png', fullPage: true });
  await page.goto('/write');
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.goto('/guestbooks/nonexistent');
  await expect(page.getByText('이 방명록을 찾을 수 없어요.')).toBeVisible();
});
